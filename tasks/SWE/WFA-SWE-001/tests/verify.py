#!/usr/bin/env python3
"""Harbor verifier for WorkflowArena sci-pr (C2 family).  python>=3.8, stdlib only.

Runs inside the verifier image (same pinned dependency layers as the agent image,
but WITHOUT the target package installed).  Input: the agent's source tree collected
from the agent environment at /work (Harbor artifact).  Nothing from the agent
environment is imported; the tree is rebuilt from source here.

Steps
  1. tamper check against /tests/start-manifest.json + /tests/protected-files.json
     - every protected file (all start-tree files not touched by the reference patch) must be
       byte-identical to the clean start tree
     - no new conftest.py / pytest.ini / tox.ini / setup.cfg / pyproject.toml /
       sitecustomize.py / usercustomize.py / *.pth (unless the reference patch creates it)
     - no new symlinks
  2. remove compiled / generated build products that are not part of the start tree
     (*.so *.o *.a *.pyc ..., build/, *.egg-info, .mesonpy-*, Cython-generated .c/.cpp)
     so that C / C++ / Cython code is always recompiled from the collected sources
  3. overlay the hidden tests (tests/hidden_tests, DELETE lines of hidden_tests.txt)
  4. BUILD_CMD -> IMPORT_CHECK -> TEST_CMD from /tests/task.cmds (verbatim from the
     packaged build and test commands), offline
  5. reward.txt = 1 iff not tampered, build/import ok, pytest exit 0 with 0 failed / 0 errors
     and >0 passed; reward.json adds pass_fraction = passed / (passed + failed + errors)

Exit status: 0 when a reward was written; non-zero (and no reward file) on verifier
infrastructure errors (missing hidden tests / manifests).
"""
import fnmatch
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import time
import xml.etree.ElementTree as ET

T = "/tests"
WORK = "/work"
LOG = "/logs/verifier"
FORBIDDEN_NEW = ["conftest.py", "pytest.ini", "tox.ini", "setup.cfg", "pyproject.toml",
                 "sitecustomize.py", "usercustomize.py", "*.pth"]
ART_SUFFIX = (".so", ".o", ".a", ".pyc", ".pyo", ".pyd", ".dylib", ".obj", ".lo", ".mod", ".lib", ".dll")
ART_DIRS = ("build", "__pycache__", ".eggs", ".pytest_cache", ".hypothesis", ".mypy_cache")
ART_DIR_GLOBS = ("*.egg-info", ".mesonpy-*", "*.dist-info")


def sha_file(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


def entry_hash(p):
    if os.path.islink(p):
        return "LINK:" + os.readlink(p)
    return sha_file(p)


def walk_files(root):
    out = []
    for d, dirs, files in os.walk(root):
        for x in list(dirs):  # symlinked dirs are listed as dirs; treat as entries
            if os.path.islink(os.path.join(d, x)):
                files.append(x)
                dirs.remove(x)
        for f in files:
            out.append(os.path.relpath(os.path.join(d, f), root))
    return out


def write_reward(reward, nums, details):
    os.makedirs(LOG, exist_ok=True)
    with open(os.path.join(LOG, "details.json"), "w") as f:
        json.dump(details, f, indent=1, ensure_ascii=False)
    nums = dict(nums)
    nums["reward"] = float(reward)
    with open(os.path.join(LOG, "reward.json"), "w") as f:
        json.dump(nums, f, indent=1)
    with open(os.path.join(LOG, "reward.txt"), "w") as f:
        f.write("%s\n" % (1 if reward else 0))
    print("REWARD", reward, json.dumps(nums))


def zero(reason, details, extra=None):
    nums = {"pass_fraction": 0.0, "passed": 0, "failed": 0, "errors": 0, "skipped": 0,
            "tampered": 1 if reason == "tampered" else 0, "build_ok": 0, "import_ok": 0,
            "artifact_present": 0 if reason == "no_artifact" else 1}
    if extra:
        nums.update(extra)
    details["fail_reason"] = reason
    write_reward(0, nums, details)
    sys.exit(0)


def is_artifact(rel):
    parts = rel.split("/")
    base = parts[-1]
    if base.endswith(ART_SUFFIX) or ".so." in base or ".cpython-" in base and base.endswith(".so"):
        return True
    for p in parts[:-1]:
        if p in ART_DIRS or any(fnmatch.fnmatch(p, g) for g in ART_DIR_GLOBS):
            return True
    return False


def cython_generated(path):
    if not path.endswith((".c", ".cpp", ".cxx", ".h")):
        return False
    try:
        with open(path, "rb") as f:
            head = f.read(400)
    except OSError:
        return False
    return b"Generated by Cython" in head


def run(cmd, logname, timeout, env):
    t0 = time.time()
    with open(os.path.join(LOG, logname), "w") as lf:
        try:
            p = subprocess.run(["bash", "-c", cmd], stdout=lf, stderr=subprocess.STDOUT, env=env, timeout=timeout)
            rc = p.returncode
        except subprocess.TimeoutExpired:
            lf.write("\nVERIFIER TIMEOUT after %ss\n" % timeout)
            rc = 124
    return rc, round(time.time() - t0, 1)


def parse_junit(path):
    res = {}
    rank = {"passed": 0, "skipped": 1, "failed": 2, "error": 3}
    try:
        root = ET.parse(path).getroot()
    except Exception:
        return None
    for tc in root.iter("testcase"):
        tid = "%s::%s" % (tc.get("classname", ""), tc.get("name", ""))
        st = "passed"
        for ch in tc:
            if ch.tag == "error":
                st = "error"
            elif ch.tag == "failure" and st != "error":
                st = "failed"
            elif ch.tag == "skipped" and st == "passed":
                st = "skipped"
        if tid not in res or rank[st] > rank[res[tid]]:
            res[tid] = st
    return res


def parse_summary(txt):
    txt = re.sub(r"\x1b\[[0-9;]*m", "", txt)
    line = None
    for l in txt.splitlines():
        if re.search(r"\d+ (passed|failed|errors?|skipped)", l) and re.search(r" in [\d.]+s", l):
            line = l.strip().strip("=").strip()
    c = {"passed": 0, "failed": 0, "errors": 0, "skipped": 0}
    if line:
        for n, k in re.findall(r"(\d+) (passed|failed|errors?|skipped)", line):
            c["errors" if k.startswith("error") else k] += int(n)
    return line, c


def load_env(path):
    out = subprocess.run(["bash", "-c", "set -a; . %s; printf '%%s\\0%%s\\0%%s' \"$BUILD_CMD\" \"$IMPORT_CHECK\" \"$TEST_CMD\"" % path],
                         stdout=subprocess.PIPE, check=True).stdout.decode()
    b, i, t = out.split("\0")
    return b, i, t


def main():
    t_start = time.time()
    os.makedirs(LOG, exist_ok=True)
    for f in ("reward.txt", "reward.json"):
        if os.path.exists(os.path.join(LOG, f)):
            os.remove(os.path.join(LOG, f))
    try:
        manifest = json.load(open(os.path.join(T, "start-manifest.json")))["files"]
        prot = json.load(open(os.path.join(T, "protected-files.json")))
        build_cmd, import_cmd, test_cmd = load_env(os.path.join(T, "task.cmds"))
        hidden_root = os.path.join(T, "hidden_tests")
        hidden_list = [l.rstrip("\n") for l in open(os.path.join(T, "hidden_tests.txt")) if l.strip()]
        assert os.path.isdir(hidden_root) and hidden_list
    except Exception as e:  # verifier infrastructure problem: do not write a reward
        sys.stderr.write("verifier setup error: %r\n" % (e,))
        sys.exit(3)
    details = {"task": prot.get("task"), "verifier": "WorkflowArena sci-pr C2 verifier v1"}

    if not os.path.isdir(WORK) or not os.listdir(WORK):
        zero("no_artifact", details)

    # ---- 1. tamper check ----
    viol = []
    for rel, h in sorted(prot["files"].items()):
        p = os.path.join(WORK, rel)
        if not os.path.lexists(p):
            viol.append(["protected_missing", rel])
        elif os.path.islink(p) or not os.path.isfile(p) or sha_file(p) != h:
            viol.append(["protected_modified", rel])
    allowed_new = set(prot.get("allowed_new", []))
    files = walk_files(WORK)
    for rel in files:
        if rel in manifest or rel in allowed_new:
            continue
        p = os.path.join(WORK, rel)
        if os.path.islink(p):
            viol.append(["symlink_created", rel])
        elif any(fnmatch.fnmatch(os.path.basename(rel), g) for g in FORBIDDEN_NEW) and not is_artifact(rel):
            viol.append(["forbidden_new_file", rel])
    for rel, h in manifest.items():  # pre-existing symlinks must keep their target
        if h.startswith("LINK:"):
            p = os.path.join(WORK, rel)
            if os.path.lexists(p) and (not os.path.islink(p) or "LINK:" + os.readlink(p) != h):
                viol.append(["symlink_modified", rel])
    details["tamper"] = {"protected_checked": len(prot["files"]), "violations": viol[:100], "n_violations": len(viol)}
    if viol:
        zero("tampered", details)

    # ---- 2. clean build products not in the start tree ----
    removed = 0
    for rel in files:
        if rel in manifest:
            continue
        p = os.path.join(WORK, rel)
        if is_artifact(rel) or cython_generated(p):
            os.remove(p)
            removed += 1
    for d, dirs, fs in os.walk(WORK, topdown=False):  # drop now-empty artifact dirs
        b = os.path.basename(d)
        if d != WORK and (b in ART_DIRS or any(fnmatch.fnmatch(b, g) for g in ART_DIR_GLOBS)):
            try:
                os.rmdir(d)
            except OSError:
                pass
    details["build_products_removed"] = removed

    # ---- 3. overlay hidden tests ----
    for d, dirs, fs in os.walk(hidden_root):
        for f in fs:
            src = os.path.join(d, f)
            rel = os.path.relpath(src, hidden_root)
            dst = os.path.join(WORK, rel)
            if os.path.lexists(dst) and (os.path.islink(dst) or os.path.isdir(dst)):
                shutil.rmtree(dst) if os.path.isdir(dst) and not os.path.islink(dst) else os.remove(dst)
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            shutil.copy2(src, dst)
    for l in hidden_list:
        if l.startswith("DELETE "):
            p = os.path.join(WORK, l[7:].strip())
            if os.path.lexists(p):
                os.remove(p)

    # ---- 4. build, import, test (offline) ----
    env = dict(os.environ)
    env.setdefault("OPENBLAS_CORETYPE", "Haswell")
    env.setdefault("MPLBACKEND", "Agg")
    env.setdefault("OMP_NUM_THREADS", "4")
    junit = "/tmp/wfs-junit.xml"
    if os.path.exists(junit):
        os.remove(junit)
    env["PYTEST_ADDOPTS"] = (env.get("PYTEST_ADDOPTS", "") + " --junitxml=%s" % junit).strip()
    timings = {}
    rc_b, timings["build_s"] = run(build_cmd, "build.log", 6000, env)
    rc_i, timings["import_s"] = run(import_cmd, "import.log", 600, env) if rc_b == 0 else (None, 0)
    details.update(build_exit=rc_b, import_exit=rc_i)
    if rc_b != 0 or rc_i != 0:
        details["timings"] = timings
        zero("build_failed" if rc_b != 0 else "import_failed", details,
             {"build_ok": 1 if rc_b == 0 else 0, "import_ok": 0})
    rc_t, timings["test_s"] = run(test_cmd, "test.log", 5400, env)
    if os.path.exists("/tmp/test.log"):
        shutil.copy("/tmp/test.log", os.path.join(LOG, "pytest.log"))
    if os.path.exists(junit):
        shutil.copy(junit, os.path.join(LOG, "junit.xml"))
    txt = open(os.path.join(LOG, "pytest.log"), errors="replace").read() if os.path.exists(os.path.join(LOG, "pytest.log")) else ""
    line, c = parse_summary(txt)
    jres = parse_junit(junit) if os.path.exists(junit) else None
    if jres:
        jc = {"passed": 0, "failed": 0, "error": 0, "skipped": 0}
        for v in jres.values():
            jc[v] += 1
        counts = {"passed": jc["passed"], "failed": jc["failed"], "errors": jc["error"], "skipped": jc["skipped"]}
        # collection errors of whole files are reported by pytest but may be absent from junit
        counts["errors"] = max(counts["errors"], c["errors"])
        counts["failed"] = max(counts["failed"], c["failed"])
        details["failed_ids"] = sorted(k for k, v in jres.items() if v in ("failed", "error"))[:200]
    else:
        counts = c
    tot = counts["passed"] + counts["failed"] + counts["errors"]
    frac = round(counts["passed"] / tot, 6) if tot else 0.0
    ok = rc_t == 0 and counts["failed"] == 0 and counts["errors"] == 0 and counts["passed"] > 0
    timings["total_s"] = round(time.time() - t_start, 1)
    details.update(test_exit=rc_t, pytest_summary=line, timings=timings, counts=counts)
    nums = {"pass_fraction": frac, "passed": counts["passed"], "failed": counts["failed"],
            "errors": counts["errors"], "skipped": counts["skipped"], "tampered": 0,
            "build_ok": 1, "import_ok": 1, "artifact_present": 1, "test_exit": rc_t}
    write_reward(1 if ok else 0, nums, details)


if __name__ == "__main__":
    main()
